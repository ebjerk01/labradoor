#!/usr/bin/env python3
"""Write a hash-locked requirements file for a connector's venv (security review 2026-11-15, L9).

    python3 deploy/pin-requirements.py connectors/ai/requirements.in > connectors/ai/requirements.txt

The input lists EVERY package with an exact version (`name==version`, the full dependency closure: take it from
`pip freeze` of a venv that works). For each one this asks PyPI for the sha256 of the WHEELS that can install on a
Labradoor container (CPython 3.13 or a pure-Python wheel; Linux x86_64 / aarch64). The output is what
deploy/lab-connector-helper installs with `pip install --require-hashes --only-binary :all: --no-deps`: no sdist (no
build script runs), no resolver, nothing that isn't listed with its hash. It lives in the signed release tree."""
import json
import re
import sys
import urllib.request

OK_TAG = re.compile(r"-(py3|py2\.py3|cp3\d*)-(none|abi3|cp313)-(any|manylinux[^-]*_(x86_64|aarch64)|musllinux[^-]*_(x86_64|aarch64))\.whl$")


def wheel_ok(name):
    if not name.endswith(".whl") or not OK_TAG.search(name):
        return False
    m = re.search(r"-(cp3\d+)-(cp3\d+|abi3|none)-", name)
    if m and m.group(2).startswith("cp3") and m.group(2) != "cp313":
        return False
    return True


def main(path):
    out = ["# hash-locked: pip install --require-hashes --only-binary :all: --no-deps -r requirements.txt",
           f"# generated by deploy/pin-requirements.py from {path.rsplit('/', 1)[-1]}; regenerate, never edit by hand"]
    for line in open(path, encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        m = re.fullmatch(r"([A-Za-z0-9._-]+)==([A-Za-z0-9.+-]+)", line)
        if not m:
            sys.exit(f"{line}: name==version only")
        name, ver = m.groups()
        with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{ver}/json", timeout=30) as r:
            files = json.load(r)["urls"]
        hashes = sorted({f["digests"]["sha256"] for f in files if wheel_ok(f["filename"])})
        if not hashes:
            sys.exit(f"{name}=={ver}: no wheel for CPython 3.13 on Linux x86_64/aarch64")
        out.append(f"{name}=={ver} \\")
        out += [f"    --hash=sha256:{h}" + (" \\" if i < len(hashes) - 1 else "") for i, h in enumerate(hashes)]
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
